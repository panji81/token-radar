// Token Radar's value model (radar-2): one sealed snapshot in, one ranked board out.
//
// The board ranks pre-token protocols — protocols whose DefiLlama record carries no token — by an
// implied value computed only from the snapshot's own figures: TVL, seven-day TVL change, and the
// time since the protocol was first listed. No protocol name is ever special-cased; the same
// function scores every row, and the dashboard states the constants so a reader can check them.
//
//   base      = tvl_usd x 0.30
//   growth    = clamp(change_7d, -80, 150) per cent
//   growthMul = 1 + (growth / 100) x 0.6
//   ageMul    = 0.5 + min(age_days, 1460) / 1460 x 0.5   (age unknown: 180 days)
//   implied   = max(1, round(base x growthMul x ageMul))
//
// Growth is clamped hard because the snapshot's largest seven-day move is over 4,000%: without the
// clamp one week's spike would outrank years of TVL. Age is capped at four years so an old
// protocol cannot outrun a younger one on seniority alone.
//
// Selection: the watchlist is the floor — all 40 of its slugs are ranked. The early radar then
// takes the 160 pre-token protocols below the $50M floor with the highest implied value, so the
// early cut is made by the model itself, not by raw TVL. Live-token protocols (a token already
// trades) are never ranked: they are set aside with their market caps, the market's own numbers.

/** One protocol entry of the sealed snapshot: exactly its ten fields. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole sealed snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.3,
  growth_weight: 0.6,
  growth_floor: -80,
  growth_cap: 150,
  maturity_floor: 0.5,
  maturity_range: 0.5,
  maturity_days: 1460,
  unknown_age_days: 180,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'radar-2';

/** How many pre-token protocols below the watchlist floor the early radar carries. */
export const EARLY_ROWS = 160;

/** How many live-token protocols the Live token view carries, by market cap. */
export const LIVE_ROWS = 20;

